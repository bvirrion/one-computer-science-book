// The generator: its output is the checked-in table file, and the parser
// built on it agrees with chapter 2's parser.
#[path = "../../02-top-down-parsing/listings/grammar.rs"]
mod grammar;
#[path = "../listings/lr0.rs"]
mod lr0;
#[path = "../listings/slr.rs"]
mod slr;
#[path = "../listings/gen.rs"]
mod gen;

#[test]
fn the_tables_file_is_the_generator_output() {
    let g = grammar::Grammar::parse(&std::fs::read_to_string("../listings/moor_expr.grammar").unwrap());
    let src = gen::emit("moor_expr.grammar", &g).unwrap();
    assert_eq!(src, std::fs::read_to_string("../listings/moor_expr_tables.rs").unwrap());
    assert!(src.starts_with("// Generated by lrgen from moor_expr.grammar: 56 states."));
    let amb = grammar::Grammar::parse(&std::fs::read_to_string("../exercises/ambig.grammar").unwrap());
    assert!(gen::emit("ambig.grammar", &amb).unwrap_err().starts_with("conflict in state"));
}
