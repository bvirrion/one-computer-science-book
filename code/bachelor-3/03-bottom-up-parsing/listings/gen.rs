// gen.rs -- a parser generator: from a grammar, the Rust source of its SLR
// tables. 0 is an error, k > 0 shifts to state k - 1, k < 0 reduces by rule
// -k - 1, ACCEPT accepts.
#![allow(dead_code)]
use crate::grammar::Grammar;
use crate::lr0;
use crate::slr::{self, Action};

pub fn emit(name: &str, g: &Grammar) -> Result<String, String> {
    let g = lr0::augment(g);
    let a = lr0::automaton(&g);
    let t = slr::table(&g, &a);
    if let Some(((s, x), _)) = slr::conflicts(&t).first() {
        return Err(format!("conflict in state {s} on {x}"));
    }
    let mut terms: Vec<&str> = vec![];
    for (_, rhs) in &g.rules {
        for s in rhs.iter().filter(|s| !g.is_nt(s)) {
            if !terms.contains(&s.as_str()) {
                terms.push(s);
            }
        }
    }
    terms.push("$");
    let q = |v: &[&str]| v.iter().map(|s| format!("{s:?}")).collect::<Vec<_>>().join(", ");
    let mut out = format!("// Generated by lrgen from {name}: {} states. Do not edit.\n", a.states.len());
    out += "pub const ACCEPT: i16 = i16::MAX;\n";
    out += &format!("pub const TERMINALS: &[&str] = &[{}];\n", q(&terms));
    let nts: Vec<&str> = g.nonterms.iter().map(|s| s.as_str()).collect();
    out += &format!("pub const NONTERMS: &[&str] = &[{}];\n", q(&nts));
    out += "pub const RULES: &[(&str, &[&str])] = &[\n";
    for (lhs, rhs) in &g.rules {
        let r: Vec<&str> = rhs.iter().map(|s| s.as_str()).collect();
        out += &format!("    ({lhs:?}, &[{}]),\n", q(&r));
    }
    out += "];\npub const ACTION: &[[i16; ";
    out += &format!("{}]] = &[\n", terms.len());
    for k in 0..a.states.len() {
        let row: Vec<String> = terms.iter().map(|x| match t.action.get(&(k, x.to_string())).map(|v| v[0]) {
            Some(Action::Shift(j)) => (j + 1).to_string(),
            Some(Action::Reduce(r)) => format!("-{}", r + 1),
            Some(Action::Accept) => "ACCEPT".into(),
            None => "0".into(),
        }).collect();
        out += &format!("    [{}],\n", row.join(", "));
    }
    out += &format!("];\npub const GOTO: &[[u16; {}]] = &[\n", nts.len());
    for k in 0..a.states.len() {
        let row: Vec<String> = nts.iter().map(|x| t.goto.get(&(k, x.to_string())).map_or(0, |j| *j).to_string()).collect();
        out += &format!("    [{}],\n", row.join(", "));
    }
    out += "];\n";
    Ok(out)
}
